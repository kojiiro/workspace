// Regenerates packages/gateway/src/storage/schema.generated.ts from the reviewed
// DDL in docs/sqlite-team-schema.sql so the application embeds exactly that SQL.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const sqlPath = fileURLToPath(new URL("../docs/sqlite-team-schema.sql", import.meta.url));
const outPath = fileURLToPath(new URL("../packages/gateway/src/storage/schema.generated.ts", import.meta.url));
const sql = readFileSync(sqlPath, "utf8").replace(/\r\n/g, "\n");
if (/[`\\]|\$\{/.test(sql)) throw new Error("Schema contains characters that cannot be embedded safely.");
writeFileSync(outPath,
  "// GENERATED by scripts/sync-schema.mjs from docs/sqlite-team-schema.sql. Do not edit.\n" +
  "export const SCHEMA_V2_SQL = `" + sql + "`;\n");
console.log("Wrote", outPath);
